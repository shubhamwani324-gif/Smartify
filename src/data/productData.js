// Helper to calculate exact restock recommendation using inventory formula:
// Recommended Restock = max(0, Estimated Demand * (1 + Safety Buffer) - Current Stock)
export function calculateRestockRecommendation(item, customBuffer) {
  const buffer = customBuffer !== undefined ? customBuffer : (item.bufferPercent / 100);
  const targetInventory = Math.ceil(item.estimatedDemand * (1 + buffer));
  const recommendedQty = Math.max(0, targetInventory - item.currentStock);
  const estimatedCost = recommendedQty * item.unitCost;
  const estimatedGrossRevenue = recommendedQty * item.retailPrice;
  return {
    recommendedQty,
    targetInventory,
    estimatedCost,
    estimatedGrossRevenue,
    safetyUnits: Math.ceil(item.estimatedDemand * buffer)
  };
}
